export function translate(lang, key, values = {}) {
  if (typeof key !== "string") return key;
  const dictionary = translations[lang];
  const plural = typeof values.count === "number"
    ? new Intl.PluralRules(dictionary ? lang : "en").select(values.count)
    : null;
  const pluralKey = plural ? key + "." + plural : key;
  const text = dictionary && Object.hasOwn(dictionary, pluralKey)
    ? dictionary[pluralKey]
    : dictionary && Object.hasOwn(dictionary, key) ? dictionary[key] : key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder
  );
}
